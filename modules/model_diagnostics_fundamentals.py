from __future__ import annotations

import streamlit as st

from utils.ui import chips, navigate, teaching_table, workspace_header


ACCENT = "#fb7185"


def _concept_card(title: str, body: str, accent: str = ACCENT) -> None:
    st.markdown(
        f"""
        <div class='teaching-card' style='--teach-accent:{accent};'>
            <div class='teaching-card-title'>{title}</div>
            <div class='teaching-card-body'>{body}</div>
        </div>
        """,
        unsafe_allow_html=True,
    )


def _equation_caption(text: str) -> None:
    st.markdown(f"<div class='equation-caption'>{text}</div>", unsafe_allow_html=True)


def render() -> None:
    workspace_header(
        "Model Diagnostics Fundamentals",
        "After kinetic fitting: distinguish data consistency, dynamic model adequacy, parameter identifiability and support for individual kinetic terms.",
        section="Model Diagnostics",
        accent=ACCENT,
    )

    chips([
        ("Learning", "blue"),
        ("Post-fit diagnostics", ""),
        ("Stoichiometric consistency", "blue"),
        ("Data reconciliation", "warn"),
        ("Residuals", ""),
        ("Profile likelihood", "warn"),
    ])

    st.markdown(
        """
        <div class='learning-objectives'>
            <div class='learning-objectives-title'>Diagnostic path</div>
            <div class='learning-objectives-grid'>
                <div><b>1 · Check data</b><br><span>against rate-free stoichiometric constraints.</span></div>
                <div><b>2 · Inspect residuals</b><br><span>for systematic unexplained structure.</span></div>
                <div><b>3 · Challenge parameters</b><br><span>for correlation and weak identifiability.</span></div>
                <div><b>4 · Test structure</b><br><span>to ask whether individual kinetic terms are needed.</span></div>
            </div>
        </div>
        """,
        unsafe_allow_html=True,
    )

    st.markdown("## Fitting is not the end of modelling")
    st.markdown(
        "A successful optimisation shows that an algorithm has found parameter values that minimise the chosen objective function. "
        "It does **not** automatically show that the measurements are internally consistent, the residuals resemble experimental error, "
        "the fitted parameters are uniquely identified, every kinetic term is required, or the assumed mechanism is physically correct."
    )
    _concept_card(
        "The post-fit question",
        "A convincing trajectory is only the beginning. A fitted model must be examined at several different levels before the parameter values are treated as scientifically meaningful.",
        ACCENT,
    )
    st.latex(
        r"\boxed{\text{Data consistency}}\;\longrightarrow\;"
        r"\boxed{\text{Residual behaviour}}\;\longrightarrow\;"
        r"\boxed{\text{Parameter certainty}}\;\longrightarrow\;"
        r"\boxed{\text{Model structure}}"
    )
    st.markdown(
        "These diagnostics answer different questions. A model can perform well in one category and poorly in another."
    )

    st.markdown("## Data consistency before kinetic adequacy")
    st.markdown(
        "Before asking whether the **kinetic rate law** explains the observations, first ask whether the measurements are compatible with the assumed **stoichiometry**. "
        "Stoichiometric constraints depend on the reaction network but not on fitted rate constants, so they can provide a powerful rate-free check."
    )
    st.markdown("For a closed batch reactor,")
    st.latex(r"\frac{d\mathbf n}{dt}=V\,\mathbf S\,\mathbf r")
    st.markdown(r"and with the differential reaction-extent vector $d\boldsymbol\xi=V\mathbf r\,dt$,")
    st.latex(r"\boxed{d\mathbf n=\mathbf S\,d\boldsymbol\xi}")
    st.markdown(r"Any vector $\mathbf l$ satisfying")
    st.latex(r"\boxed{\mathbf l^T\mathbf S=\mathbf 0^T}")
    st.markdown("defines a stoichiometric invariant:")
    st.latex(r"\boxed{\mathbf l^T\mathbf n=\text{constant}}")
    st.latex(r"\boxed{\mathbf l^T\Delta\mathbf n=0}")
    _concept_card(
        "Rate-free information",
        "An invariant must hold for every trajectory generated by the assumed reaction network, irrespective of reaction orders, Arrhenius parameters or fitted rate constants.",
        "#2dd4bf",
    )

    st.markdown("## Which balances are genuinely independent checks?")
    teaching_table(
        ["Balance type", "Valid use"],
        [
            ["Fully observed invariant", "Calculate directly from measured species; strong rate-free measurement-consistency check."],
            ["Partially observed invariant", "Do not call it a closed measured balance; an unmeasured species must first be estimated or reconstructed."],
            ["Elemental / charge balance", "Often a strong structural check when molecular formulae, ionic states and phase boundaries are known."],
            ["Model-predicted total", "Useful after fitting, but not an independent pre-fit data-quality check."],
            ["Open-system balance", "Must include feed, outlet, sampling, evaporation/gas transfer and volume-change terms."],
        ],
        alignments=["left", "left"],
    )
    st.markdown(
        "A **partially observed invariant** remains chemically valid, but if its missing species comes from the fitted model then the resulting balance is no longer independent of that model."
    )

    st.markdown("## Worked example: biodiesel stoichiometric consistency")
    st.markdown("For the three consecutive reversible transesterification steps")
    st.latex(r"TG+MeOH\rightleftharpoons DG+ME")
    st.latex(r"DG+MeOH\rightleftharpoons MG+ME")
    st.latex(r"MG+MeOH\rightleftharpoons Gly+ME")
    st.markdown("the four measured lipid/ester species satisfy the fully observed invariant")
    _equation_caption("Fully observed fatty-acyl balance")
    st.latex(r"\boxed{3n_{TG}+2n_{DG}+n_{MG}+n_{ME}=\text{constant}}")
    st.markdown("For a constant-volume experiment this can be written in concentration form:")
    st.latex(r"\boxed{3C_{TG}+2C_{DG}+C_{MG}+C_{ME}=\text{constant}}")
    st.markdown("Define")
    st.latex(r"B(t)=3C_{TG}(t)+2C_{DG}(t)+C_{MG}(t)+C_{ME}(t)")
    st.markdown("and the normalised balance deviation")
    st.latex(r"\boxed{\varepsilon_B(t)=\frac{B(t)-B(0)}{B(0)}}")
    st.markdown(
        r"Perfectly stoichiometrically consistent measurements would give $\varepsilon_B=0$. Real experimental data normally deviate because measurements, sampling and process boundaries are imperfect."
    )
    _concept_card(
        "Why this example is strong",
        "TG, DG, MG and methyl ester are all measured. The balance can therefore be calculated from the raw observations without using methanol, glycerol, fitted rate constants or a kinetic simulation.",
        "#38bdf8",
    )

    st.markdown("## Stoichiometric-consistency monitoring")
    st.markdown(
        "Plotting a balance residual through time is useful for detecting drift and systematic inconsistency. This is described as **stoichiometric-consistency monitoring**, rather than a classical statistical process control chart."
    )
    st.latex(r"e_B(t)=\mathbf l^T\Delta\mathbf n(t)")
    st.markdown(
        "Measurements within one reacting batch are serially related because the process itself is evolving. Ordinary Shewhart assumptions of independent observations from a stable process therefore do not hold literally."
    )
    _concept_card(
        "Important — drift is not automatically chemistry",
        "A smooth balance trend is evidence of inconsistency. It is not, by itself, proof of a missing reaction or a defective kinetic rate law.",
        "#f59e0b",
    )

    with st.expander("Troubleshooting a systematic balance drift"):
        st.markdown(
            "Check plausible experimental and bookkeeping causes before escalating the chemistry, approximately in this order:"
        )
        st.markdown(
            "1. incorrect unit conversion or molecular-weight basis;  \n"
            "2. instrumental calibration slope/intercept error;  \n"
            "3. changing detector sensitivity or dilution;  \n"
            "4. sampling-volume removal;  \n"
            "5. evaporation, headspace transfer, venting or leakage;  \n"
            "6. phase partitioning;  \n"
            "7. changing reactor volume, density or flow;  \n"
            "8. an unmeasured species;  \n"
            "9. an omitted side reaction;  \n"
            "10. incorrect stoichiometric coefficients or molecular formula;  \n"
            "11. an incorrect process boundary;  \n"
            "12. genuine model mismatch."
        )
        st.markdown(
            "Stoichiometric constraints are valuable precisely because they can reveal inconsistency **before** the kinetic rate law is blamed."
        )

    st.markdown("## Data reconciliation: move the measurements as little as possible")
    st.markdown(
        "Stoichiometric monitoring identifies inconsistency. **Data reconciliation** asks a second question: what is the smallest statistically plausible adjustment to the measurements that makes them satisfy the trusted constraints?"
    )
    st.markdown(r"Let $\mathbf y$ be the measured vector, $\mathbf x$ the reconciled estimate, and suppose exact linear constraints are")
    st.latex(r"\boxed{\mathbf H\mathbf x=\mathbf h}")
    st.markdown(r"With measurement-error covariance matrix $\boldsymbol\Sigma$, weighted reconciliation solves")
    st.latex(
        r"\boxed{\min_{\mathbf x}(\mathbf x-\mathbf y)^T\boldsymbol\Sigma^{-1}(\mathbf x-\mathbf y)}"
    )
    st.markdown(r"subject to $\mathbf H\mathbf x=\mathbf h$. For linear constraints,")
    st.latex(
        r"\boxed{\mathbf x^*=\mathbf y-\boldsymbol\Sigma\mathbf H^T"
        r"(\mathbf H\boldsymbol\Sigma\mathbf H^T)^{-1}(\mathbf H\mathbf y-\mathbf h)}"
    )
    st.markdown("The measurement correction is")
    st.latex(r"\boxed{\boldsymbol\delta=\mathbf x^*-\mathbf y}")
    st.markdown("and a weighted inconsistency measure is")
    st.latex(
        r"\boxed{J_{rec}=(\mathbf x^*-\mathbf y)^T\boldsymbol\Sigma^{-1}(\mathbf x^*-\mathbf y)}"
    )
    st.markdown(
        "Measurements assigned larger uncertainty are allowed to move more than precise measurements. If uncertainty information is unavailable, an equal-weight reconciliation may be useful, but it must be labelled because it assumes all channels are equally reliable."
    )
    _concept_card(
        "Raw measurements must remain visible",
        "Reconciliation is a diagnostic aid, not permission to hide poor data. Raw observations are retained and distinguished from reconciled estimates. Fitting reconciled data is a separate sensitivity analysis, not a replacement for the original measurements.",
        "#fb7185",
    )

    st.markdown("## Dynamic residual diagnostics")
    st.markdown(
        "Once data consistency has been considered, residuals ask whether the **dynamic kinetic model** leaves systematic information unexplained. Define"
    )
    st.latex(r"\boxed{e_i(t_j)=y_i^{model}(t_j)-y_i^{obs}(t_j)}")
    st.markdown(
        "KineticFittingPot retains the fitting-engine sign convention: model minus observation. A visually convincing fitted trajectory can still conceal residual drift, species-specific bias or experiment-specific structure."
    )
    teaching_table(
        ["Diagnostic view", "What it can reveal"],
        [
            ["Residual versus time", "Drift, early/late bias, oscillation or omitted dynamics."],
            ["Residual versus fitted value", "Changing variance, curvature or systematic under/overprediction."],
            ["Residual by species", "One assay or species dominating the mismatch."],
            ["Residual by experiment", "Initial-condition, temperature or batch-specific model failure."],
            ["Q–Q / empirical distribution", "Gross tails, skew and unusual outliers."],
            ["Cross-species residual correlation", "Shared measurement or model errors across channels."],
        ],
        alignments=["left", "left"],
    )

    st.markdown("### Scaled is not the same as statistically standardised")
    st.markdown(r"If a meaningful experimental standard deviation $\sigma_i$ is known,")
    st.latex(r"\boxed{z_i=\frac{e_i}{\sigma_i}}")
    st.markdown(
        "can be interpreted as an uncertainty-standardised residual. If KineticFittingPot divides only by a numerical species scale $s_i$,"
    )
    st.latex(r"e_i^{scaled}=\frac{e_i}{s_i}")
    st.markdown("the result should be called a **scaled residual**, not a formal statistically standardised residual.")

    st.markdown("### Autocorrelation needs appropriate sampling")
    st.markdown(
        "Residuals that remain related in time may indicate missing dynamics. For approximately regularly sampled residuals, an autocorrelation function can be informative:"
    )
    st.latex(r"\rho(k)=\operatorname{corr}(e_j,e_{j-k})")
    _concept_card(
        "Do not manufacture a regular grid",
        "KineticFittingPot supports irregular observation schedules. A conventional residual ACF is appropriate only when sampling is sufficiently regular. Experimental residuals are not silently interpolated to manufacture an ACF.",
        "#a78bfa",
    )
    st.markdown(
        "Likewise, cross-species residual relationships should use genuinely corresponding observation times unless an explicit interpolation method has been justified."
    )

    st.markdown("## Parameter certainty is not optimiser convergence")
    st.markdown(
        "Many multistart runs reaching the same optimum improves confidence that the numerical optimiser has found the same basin. It does **not** prove that each fitted parameter is well identified. Different parameter combinations can sometimes generate almost indistinguishable trajectories."
    )

    st.markdown("## Local sensitivity and parameter correlation")
    st.markdown(r"For residual vector $\mathbf e(\boldsymbol\theta)$, the local Jacobian is")
    st.latex(r"\boxed{J_{ij}=\frac{\partial e_i}{\partial\theta_j}}")
    st.markdown(
        "Each column describes how the residual pattern changes when one fitted parameter changes. Nearly proportional columns indicate that parameters may trade off strongly."
    )
    st.markdown("Under the usual local least-squares approximation,")
    st.latex(r"\boxed{\operatorname{Cov}(\hat{\boldsymbol\theta})\approx s^2(\mathbf J^T\mathbf J)^{-1}}")
    st.markdown("and the corresponding local parameter correlation is")
    st.latex(
        r"\boxed{\rho_{ij}=\frac{\operatorname{Cov}_{ij}}"
        r"{\sqrt{\operatorname{Cov}_{ii}\operatorname{Cov}_{jj}}}}"
    )
    _concept_card(
        "Interpret correlation carefully",
        "Very high parameter correlation means the experiment may identify a parameter combination much more strongly than the individual parameters. Covariance calculations are local approximations and can be misleading for strongly nonlinear objectives or parameters near bounds.",
        "#38bdf8",
    )

    st.markdown("## Profile likelihood: deliberately move one parameter")
    st.markdown(
        "Profile likelihood asks how much the fit deteriorates when one parameter is forced away from its optimum while every other fitted parameter is re-optimised. "
        "For KineticFittingPot's least-squares fits, the directly computed quantity is a **profiled objective**; under an appropriate Gaussian measurement-error model this is equivalent to a profile-likelihood view up to scaling and constants."
    )
    st.markdown(r"For a fixed trial value $\theta_j^*$,")
    st.latex(
        r"\boxed{Q_p(\theta_j^*)="
        r"\min_{\boldsymbol\theta_{-j}}Q(\theta_j^*,\boldsymbol\theta_{-j})}"
    )
    teaching_table(
        ["Profile shape", "Interpretation"],
        [
            ["Sharp interior minimum", "The data constrain the parameter relatively strongly."],
            ["Broad / flat profile", "Many values give almost the same fit; the parameter is weakly identified."],
            ["One-sided or bound-limited", "The experiment may support only a limit rather than a well-defined finite estimate."],
        ],
        alignments=["left", "left"],
    )
    st.markdown(
        "Profile likelihood is therefore a stronger nonlinear diagnostic than relying only on a local covariance matrix."
    )

    st.markdown("## Are reversible reactions actually supported by the data?")
    st.markdown(
        r"Reverse rate constants provide a particularly clear model-structure test. For a reverse parameter $k_r\geq0$, compare the unrestricted reversible fit with a constrained fit in which"
    )
    st.latex(r"\boxed{k_r=0}")
    st.markdown("Define")
    st.latex(r"\boxed{\Delta Q=Q_{k_r=0}-Q_{full}}")
    st.markdown(
        "If forcing $k_r=0$ produces almost no deterioration in fit quality, the experimental data do not require that reverse term. "
        "If the objective worsens substantially and the profile has a clear finite interior minimum, support for retaining the reverse term is much stronger."
    )
    _concept_card(
        "Use scientifically careful language",
        "A diagnostic may support inclusion of a reverse rate term in the empirical dynamic model. It does not prove an elementary molecular mechanism. Because zero is a parameter boundary, a simple significance test must not be treated as definitive mechanistic proof.",
        "#f59e0b",
    )

    st.markdown("## Model adequacy is not mechanistic proof")
    _concept_card(
        "Important",
        "A good fitted mass-action model does not prove that the underlying reaction mechanism is elementary mass action. It establishes that, over the experimental domain studied, the observed dynamics are adequately represented by that rate law.",
        "#2dd4bf",
    )
    st.markdown(
        "Before escalating to a more flexible intrinsic rate expression, ask whether apparent non-mass-action behaviour could instead be caused by:"
    )
    st.markdown(
        "- temperature changes not represented through $k(T)$;\n"
        "- activity rather than concentration effects;\n"
        "- changing liquid volume;\n"
        "- mixing or sampling dead time;\n"
        "- gas–liquid mass transfer;\n"
        "- adsorption, catalyst activation/deactivation or site saturation;\n"
        "- diffusion or transport limitations;\n"
        "- instrument response delay or nonlinear calibration;\n"
        "- uncertain initial conditions;\n"
        "- missing, aggregated or unmeasured species."
    )
    st.markdown(
        "A more complicated kinetic expression should not be used merely to absorb an experimental artefact or an incorrect process boundary."
    )

    st.markdown("## KineticFittingPot diagnostic workflow")
    st.latex(
        r"\boxed{\text{Raw measurements}}\rightarrow"
        r"\boxed{\text{Stoichiometric consistency}}\rightarrow"
        r"\boxed{\text{Optional reconciliation}}"
    )
    st.latex(
        r"\boxed{\text{Kinetic fit}}\rightarrow"
        r"\boxed{\text{Residual diagnostics}}\rightarrow"
        r"\boxed{\text{Parameter identifiability}}\rightarrow"
        r"\boxed{\text{Model-structure tests}}"
    )
    _concept_card(
        "Key idea",
        "Stoichiometry tests whether the data are chemically self-consistent. Residuals test whether the dynamic model leaves systematic information unexplained. Parameter diagnostics test whether fitted constants are genuinely supported by the experiment. Model-structure tests ask whether every kinetic term is actually necessary.",
        ACCENT,
    )

    st.divider()
    c1, c2 = st.columns(2)
    with c1:
        if st.button("← Open Kinetic Parameter Fitting", key="model_diag_fund_to_fit"):
            navigate("Kinetic Parameter Fitting")
    with c2:
        if st.button("Open Post-fit Model Diagnostics →", key="model_diag_fund_to_postfit"):
            navigate("Post-fit Model Diagnostics")
